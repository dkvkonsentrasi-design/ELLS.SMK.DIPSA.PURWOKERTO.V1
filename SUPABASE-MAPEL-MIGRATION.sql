-- RBAC Kelas: hanya Admin yang boleh menambah, mengubah, atau menghapus kelas.
-- Guru tetap dapat membaca data kelas untuk kebutuhan dashboard, filter siswa,
-- dan pengumpulan tugas.
alter table public.classes enable row level security;

-- Hapus policy lama pada tabel classes agar tidak ada policy permissive
-- yang masih memberikan akses tulis kepada Guru.
do $$
declare
  policy_record record;
begin
  for policy_record in
    select policyname
    from pg_policies
    where schemaname = 'public'
      and tablename = 'classes'
  loop
    execute format('drop policy if exists %I on public.classes', policy_record.policyname);
  end loop;
end $$;

create policy classes_authenticated_select_policy on public.classes
for select to authenticated
using (true);

create policy classes_admin_insert_policy on public.classes
for insert to authenticated
with check (
  exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
);

create policy classes_admin_update_policy on public.classes
for update to authenticated
using (
  exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
)
with check (
  exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
);

create policy classes_admin_delete_policy on public.classes
for delete to authenticated
using (
  exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
);
